def country_flag(item):
    """Zero-I/O country icon for Smart Sources.

    Uses Unicode regional indicators when a real ISO alpha-2 country exists;
    broad MENA/INT sources use a globe.  Sorting never depends on this glyph.
    """
    code = primary_country_code(item).upper()
    if code in ("MENA", "INT", "AR_COUNTRY"):
        if code == "AR_COUNTRY":
            code = "AR"
        else:
            return u"🌐"
    if code == "UK":
        code = "GB"
    if len(code) == 2 and code.isalpha():
        try:
            return chr(0x1F1E6 + ord(code[0]) - ord('A')) + chr(0x1F1E6 + ord(code[1]) - ord('A'))
        except Exception:
            pass
    return u"•"

def primary_country_code(item):
    countries=list((item or {}).get("countries") or [])
    # Prefer a real country over the broad MENA marker when both exist.
    for code in countries:
        if str(code) not in ("MENA", "INT"):
            return str(code)
    return str(countries[0]) if countries else "INT"

def continent_code(item):
    return _COUNTRY_CONTINENT.get(primary_country_code(item), "INTERNATIONAL")

def continent_name(item):
    return CONTINENT_NAMES.get(continent_code(item), "International / MENA")

def country_name(item):
    code=primary_country_code(item)
    return COUNTRY_NAMES.get(code, str((item or {}).get("region") or code or "Other"))

def source_category(item):
    """One flat Smart Sources category; no continent/country sub-groups."""
    provider = str((item or {}).get("provider") or "ONLINE").upper().strip()
    if provider == "EPG GROUPS":
        return "EPG GROUPS"
    if provider == "EPG SCRAPERS":
        return "EPG SCRAPERS"
    if (item or {}).get("kind") == "local" or provider == "EPG MANAGER":
        return "EPG MANAGER"
    if provider == "EPGSHARE":
        return "EPGSHARE"
    if provider == "OPENEPG":
        return "OPENEPG"
    if provider in ("RYTEC", "AZMAN", "KOALA"):
        return "RYTEC"
    return provider or "OTHER"


def smart_group(item):
    # beta65 flat provider categories: simple, predictable, SaaS-like.
    return source_category(item)

_PROVIDER_ORDER = {"EPG SCRAPERS":0, "EPG GROUPS":1, "EPGSHARE":2, "OPENEPG":3, "RYTEC":4, "AZMAN":4, "KOALA":4, "EPG MANAGER":9}
_PREFERRED_PROVIDER = {"MA":"EPG MANAGER", "MENA":"EPG MANAGER", "EG":"OPENEPG", "SA":"OPENEPG", "QA":"OPENEPG", "AE":"OPENEPG", "PS":"OPENEPG", "FR":"RYTEC", "PL":"RYTEC", "ES":"RYTEC"}


def bundled_external_sources():
    out=[]
    for src in external_sources.SOURCES:
        item=dict(src)
        item["kind"]="external"
        item["group"]=smart_group(item)
        item["dynamic"]=False
        out.append(item)
    return out


def mapping_source_id(item):
    if not item: return ""
    if item.get("kind") == "local": return str(item.get("manager_id") or item.get("id") or "")
    return str(item.get("id") or "")


def catalogue_source_id(item):
    return str((item or {}).get("id") or "")


def _natural_name(value):
    # Natural alphabetical key: "Source 2" before "Source 10".
    return tuple(int(x) if x.isdigit() else x for x in re.split(r"(\d+)", str(value or "").casefold()))


def source_sort_key(item):
    """beta65 Smart Sources order: provider category -> source A-Z only."""
    item=item or {}
    category=source_category(item)
    return (_PROVIDER_ORDER.get(category,50), _natural_name(item.get("name") or item.get("id") or ""))


def smart_source_sort_key(item, mapped_count=0, selected=False):
    """Stable category/A-Z order; selection never makes a row jump."""
    return source_sort_key(item)


def all_sources():
    global _ALL_SOURCES_CACHE
    if _ALL_SOURCES_CACHE is None:
        rows=[]
        for raw in list(LOCAL_SOURCES) + bundled_external_sources():
            item=dict(raw)
            item["group"]=smart_group(item)
            item["continent"]=continent_name(item)
            item["country_name"]=country_name(item)
            rows.append(item)
        _ALL_SOURCES_CACHE = sorted(rows, key=source_sort_key)
    # Callers historically receive a list and sometimes iterate it multiple
    # times. A shallow copy is cheap and prevents accidental append/pop from
    # corrupting the process-wide catalogue cache.
    return list(_ALL_SOURCES_CACHE)


def by_catalogue_id():
    return {x.get("id"):x for x in all_sources()}


def by_mapping_id():
    return {mapping_source_id(x):x for x in all_sources()}


