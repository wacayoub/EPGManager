def provider_bundles():
    global _PROVIDER_BUNDLES_CACHE
    if _PROVIDER_BUNDLES_CACHE is None:
        bundles=OrderedDict((code,OrderedDict()) for code in COUNTRY_NAMES)
        for item in all_sources():
            provider=str(item.get("provider") or "ONLINE").upper()
            if provider in ("AZMAN", "KOALA"):
                provider = "RYTEC"
            for code in item.get("countries") or []:
                if code not in bundles: bundles[code]=OrderedDict()
                bundles[code].setdefault(provider,[]).append(item)
        clean=OrderedDict()
        for code in COUNTRY_NAMES:
            providers=bundles.get(code) or {}
            if not providers: continue
            ordered=OrderedDict()
            for provider in sorted(providers,key=lambda p:(_PROVIDER_ORDER.get(p,50),p)):
                seen=set(); rows=[]
                for item in providers[provider]:
                    sid=item.get("id")
                    if sid in seen: continue
                    seen.add(sid); rows.append(item)
                ordered[provider]=rows
            clean[code]=ordered
        _PROVIDER_BUNDLES_CACHE = clean
    return _PROVIDER_BUNDLES_CACHE


def provider_items(country_code, provider):
    return list((provider_bundles().get(str(country_code)) or {}).get(str(provider).upper()) or [])


def default_provider(country_code):
    code=str(country_code); providers=list((provider_bundles().get(code) or {}).keys())
    preferred=_PREFERRED_PROVIDER.get(code)
    if preferred in providers: return preferred
    return providers[0] if providers else ""


def _slug(value):
    return re.sub(r"[^a-z0-9]+", "_", str(value).lower()).strip("_") or "source"


def _provider_label(country_code, provider):
    country=COUNTRY_NAMES.get(str(country_code),str(country_code))
    p=str(provider or "").upper()
    if p == "EPG SCRAPERS": return "%s EPG Scrapers Direct" % country
    if p == "EPG GROUPS": return "%s Grouped XMLTV" % country
    if p == "EPG MANAGER": return "%s EPG Manager" % country
    if p == "RYTEC": return "%s Rytec" % country
    if p in ("AZMAN", "KOALA"): return "%s Rytec" % country
    if p == "EPGSHARE": return "%s EPGShare" % country
    return "%s %s" % (country, provider)


def _openepg_label(country_code, item, count):
    """Keep numbered OpenEPG feeds visible as individual user choices.

    Morocco is intentionally displayed exactly as requested by the operator:
    Morocco 1 / Morocco 2 / Morocco EPG Manager.
    """
    country=COUNTRY_NAMES.get(str(country_code),str(country_code))
    name=str(item.get("name") or country).strip()
    if str(country_code) == "MA" and name.lower() == "morocco":
        return "Morocco 1"
    # When only one OpenEPG feed exists, make the backend clear without noise.
    if count <= 1 and name.lower() == country.lower():
        return "%s OpenEPG" % country
    return name


def source_options(country_code):
    """Return logical sources selectable by the user for one country.

    The result is cached because the catalogue is static.  This is a hot path
    on the dashboard/Source screens and must stay effectively O(1) on Vu+.
    """
    code=str(country_code)
    cached = _SOURCE_OPTIONS_CACHE.get(code)
    if cached is not None:
        return list(cached)
    providers=provider_bundles().get(code) or {}
    options=[]
    for provider in sorted(providers,key=lambda p:(_PROVIDER_ORDER.get(p,50),p)):
        items=list(providers.get(provider) or [])
        if not items: continue
        p=str(provider).upper()
        if p == "OPENEPG":
            for item in items:
                key="feed:%s" % str(item.get("id"))
                options.append({"key":key,"label":_openepg_label(code,item,len(items)),"provider":p,"items":[item]})
        else:
            key="provider:%s" % _slug(p)
            options.append({"key":key,"label":_provider_label(code,p),"provider":p,"items":items})
    _SOURCE_OPTIONS_CACHE[code] = tuple(options)
    return list(options)


def source_option(country_code, source_key):
    key=str(source_key or "")
    for option in source_options(country_code):
        if option.get("key") == key:
            return option
    # Backward compatibility: a v6.3-beta1 provider string may be passed.
    provider=key.upper()
    for option in source_options(country_code):
        if str(option.get("provider") or "").upper() == provider:
            return option
    return None


def source_option_items(country_code, source_key):
    option=source_option(country_code,source_key)
    return list((option or {}).get("items") or [])


def source_option_label(country_code, source_key):
    option=source_option(country_code,source_key)
    return str((option or {}).get("label") or source_key or "-")


def source_option_provider(country_code, source_key):
    option=source_option(country_code,source_key)
    return str((option or {}).get("provider") or "")


def default_source(country_code):
    code=str(country_code); options=source_options(code)
    if not options: return ""
    preferred=_PREFERRED_PROVIDER.get(code)
    if preferred:
        for option in options:
            if str(option.get("provider") or "").upper() == preferred:
                return str(option.get("key") or "")
    return str(options[0].get("key") or "")


def source_for_provider(country_code, provider):
    provider=str(provider or "").upper()
    for option in source_options(country_code):
        if str(option.get("provider") or "").upper() == provider:
            return str(option.get("key") or "")
    return default_source(country_code)


def country_rows():
    global _COUNTRY_ROWS_CACHE
    if _COUNTRY_ROWS_CACHE is None:
        rows=[]
        for code,name in COUNTRY_NAMES.items():
            options=source_options(code)
            if not options: continue
            rows.append({"code":code,"name":name,"sources":options,"source_keys":[x.get("key") for x in options],
                         "providers":list(OrderedDict((x.get("provider"),True) for x in options).keys())})
        _COUNTRY_ROWS_CACHE = tuple(rows)
    return list(_COUNTRY_ROWS_CACHE)


def source_contexts_for_choices(choices):
    """Build mapping contexts from (country, logical-source-key) choices."""
    contexts={}
    for country,source_key in choices or []:
        option=source_option(country,source_key)
        if not option: continue
        for item in option.get("items") or []:
            mid=mapping_source_id(item)
            provider=str(item.get("provider") or option.get("provider") or "").upper()
            row=contexts.setdefault(mid,{"countries":set(),"provider":provider,
                "catalogue_id":item.get("id"),"item":item,"source_key":option.get("key"),"source_label":option.get("label")})
            row["countries"].add(str(country))
    return contexts


def source_contexts_for_items(items):
    """Build mapping contexts directly from selected catalogue rows.

    Beta13 Smart Sources selects individual feeds with checkboxes.  Mapping
    contexts are therefore derived from those exact feed rows, not from the
    older one-source-per-country UI.  This is metadata only; the beta12/beta1
    SAT matcher remains unchanged.
    """
    contexts = {}
    for item in items or []:
        if not item:
            continue
        mid = mapping_source_id(item)
        if not mid:
            continue
        countries = set(str(x) for x in (item.get("countries") or []))
        provider = str(item.get("provider") or "").upper()
        row = contexts.setdefault(mid, {"countries": set(), "provider": provider,
            "catalogue_id": item.get("id"), "item": item,
            "source_key": "feed:%s" % str(item.get("id") or ""),
            "source_label": item.get("name") or item.get("id")})
        row["countries"].update(countries)
    return contexts
