# -*- coding: utf-8 -*-
"""Identify true beIN event-only satellite services, not normal linear channels.

beIN SPORTS MAX, XTRA, AFC may be inactive for an entire day.
No XMLTV rows are generated by this classification. It is strictly a
quality-report / completeness-audit policy, not a schedule synthesizer.
Keep original channel IDs and trust real programmes only.
"""
import re

# Full-match ID or official channel display label: avoid accidentally calling
# regular beIN 1-9, News, Movies, or unrelated AFC channels event-only.
_PATTERNS = (
    re.compile(r"^beINSportsMax[1-9][0-9]*\.qa@MENA$", re.I),
    re.compile(r"^beINSportsXtra[1-9][0-9]*\.qa@SD$", re.I),
    re.compile(r"^beINMENA\.beinsportsxtra[1-9][0-9]*$", re.I),
    re.compile(r"^beINSportsAFC[1-9]?[0-9]*(?:\.qa(?:@MENA|@SD)?)?$", re.I),
    re.compile(r"^beINMENA\.beinsportsafc[1-9]?[0-9]*$", re.I),
)
_NAME = re.compile(r"^beIN\s*(?:SPORTS?\s*)?(?:MAX|XTRA|AFC)(?:\s*[0-9]+)?$", re.I)


def is_occasional_bein(cid, names=()):
    cid = (cid or "").strip()
    if any(p.fullmatch(cid) for p in _PATTERNS):
        return True
    # All label-driven matches also require a beIN-owned ID.
    if not cid.casefold().startswith(("bein", "beinmena.")):
        return False
    return any(_NAME.fullmatch((n or "").strip()) for n in names)
